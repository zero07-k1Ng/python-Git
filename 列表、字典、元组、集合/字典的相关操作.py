t={1:'zhang',2:'wen',3:'tao',4:'shuai'}
t[5]='bi'#直接使用赋值运算符向字典中添加元素
print(t)
t1=t.keys()#获取所有key数据
print(t1)
print(list(t1))#将t1转换成列表类型输出
print(tuple(t1))
print(t.values())#获取所有value数据
t2=list(t.items())
print(t2)
d=dict(t2)#将t2转换成字典类型输出
t.pop(1)#把键为1的键值对删去
print(t)
t.popitem()#随机删除一个键值对
print(t)
t.clear()#清空字典
print(t)
print(bool(t))

