s='helloworld'
for i in range(0,len(s)):#len()序列s中元素的个数
    print(i,s[i],'',end='\t')
#切片操作
#索引从0开始，到7结束，不包括7，步长为2
s1=s[0:7:2]
print('\n',s1)
#若省略开始位置，则默认从0开始，若省略结束位置，则默认到序列的最后一个元素（包括最后一个元素），步长默认为1，
s2=s[:7:2]
print('\n',s2)
#省略开始，结束，只保留步长
s3=s[::2]
print('\n',s3)#从0开始，2，4，6，8.直到最后一个偶数个元素
print(s[-1:-11:-1])#逆序输出
print(s[::-1])
